def text():
    out = []
    for ver, lines in NEWS:
        out.append('[B]الإصدار %s[/B]' % ver)
        out.extend(lines)
        out.append('')
    return '\n'.join(out)


def show():
    xbmcgui.Dialog().textviewer('%s — وش الجديد' % ADDON_NAME, text())


def _seen():
    try:
        with open(SEEN) as f:
            return f.read().strip()
    except (IOError, OSError):
        return ''


def mark_seen():
    try:
        with open(SEEN, 'w') as f:
            f.write(ADDON.getAddonInfo('version'))
    except (IOError, OSError):
        pass


def maybe_show(monitor, first_run=False):
    """Once per new version, when the home screen is up and nothing is playing."""
    cur = ADDON.getAddonInfo('version')
    if _seen() == cur:
        return
    if first_run:
        mark_seen()          # brand-new install: the setup wizard is the welcome
        return
    for _ in range(300):     # wait up to ~15 minutes for a quiet moment
        if monitor.waitForAbort(3):
            return
        if xbmc.getCondVisibility('Window.IsActive(home)') and \
                not xbmc.getCondVisibility('Player.HasMedia') and \
                not xbmc.getCondVisibility('System.HasActiveModalDialog'):
            try:
                from .common import abtools_setup_busy
                if abtools_setup_busy():
                    continue          # Piers edition: never over AB Tools' first-run setup
            except Exception:
                pass
            break
    else:
        return
    mark_seen()
    log('showing what\'s new for %s' % cur)
    show()
