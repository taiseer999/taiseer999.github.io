# ───────────────────────── file helpers ─────────────────────────

def _read_text(path):
    with open(path, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def _write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)


def _read_bytes(path):
    try:
        with open(path, 'rb') as f:
            return f.read()
    except Exception:
        return None


def _copy_if_changed(src, dst):
    data = _read_bytes(src)
    if data is None:
        raise IOError('missing source %s' % src)
    if _read_bytes(dst) == data:
        return False
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, 'wb') as f:
        f.write(data)
    return True


def _version(addon_path):
    try:
        m = re.search(r'<addon[^>]*\sversion="([^"]+)"', _read_text(os.path.join(addon_path, 'addon.xml')))
        return m.group(1) if m else '?'
    except Exception:
        return '?'


# ───────────────────────── hooks ─────────────────────────

def _indent_of(line):
    return line[:len(line) - len(line.lstrip(' \t'))]


def _fence(code, indent, nl='\n'):
    body = ''.join(indent + ln + nl for ln in code.rstrip('\n').split('\n'))
    return '%s%s%s%s%s%s%s' % (indent, HOOK_OPEN, nl, body, indent, HOOK_CLOSE, nl)


def _apply_hooks(text, hooks):
    """Return (new_text, missing_anchors). Works on the raw text: some upstream
    files mix LF and CRLF, so each anchor is matched in either form and its
    fence uses the newline style found there (revert is then byte-exact)."""
    missing = []
    text = _strip_hooks(text)
    for _rel, anchor, code, where in hooks:
        nl, idx = '\n', text.find(anchor)
        if idx < 0:
            crlf_anchor = anchor.replace('\n', '\r\n')
            idx = text.find(crlf_anchor)
            if idx >= 0:
                nl, anchor = '\r\n', crlf_anchor
        if idx < 0:
            missing.append(anchor.strip().split('\n')[0][:60])
            continue
        if where == 'before':
            indent = _indent_of(anchor.split('\n')[0])
            text = text[:idx] + _fence(code, indent, nl) + text[idx:]
        else:
            last = anchor.rstrip('\r\n').split('\n')[-1]
            indent = '' if last.startswith(('from ', 'import ')) else _indent_of(last)
            end = idx + len(anchor)
            text = text[:end] + _fence(code, indent, nl) + text[end:]
    return text, missing


def _strip_hooks(text):
    return _HOOK_RE.sub('', text)


def _load_py(path):
    return _read_text(path), None


def _save_py(path, text, _unused=None):
    _write_text(path, text)


# ───────────────────────── apply / revert ─────────────────────────

def apply(addon_path, profile):
    """Install Lucent into one add-on. Returns (ok, message) in patcher style."""
    spec = SPECS[profile]
    aid, label = spec['addon_id'], spec['label']
    try:
        # 1. plan the Python hooks first; bail out untouched if anything is missing
        by_file = {}
        for hook in spec['hooks']:
            by_file.setdefault(hook[0], []).append(hook)
        planned, missing = {}, []
        for rel, hooks in by_file.items():
            path = os.path.join(addon_path, rel)
            if not os.path.isfile(path):
                missing.append(rel)
                continue
            text, crlf = _load_py(path)
            new_text, miss = _apply_hooks(text, hooks)
            missing += ['%s: %s' % (os.path.basename(rel), m) for m in miss]
            planned[path] = (text, new_text, crlf)
        if missing:
            return False, ('[%s] Glass theme: %s %s changed upstream, theme not applied (%s)'
                           % (aid, label, _version(addon_path), '; '.join(missing[:3])))

        written = 0
        # 2. helper module + textures
        if _copy_if_changed(os.path.join(_SRC, 'lucent_theme.py'), os.path.join(addon_path, _HELPER_REL)):
            written += 1
        media_src = os.path.join(_SRC, 'media')
        for root, _dirs, files in os.walk(media_src):
            for name in files:
                src = os.path.join(root, name)
                dst = os.path.join(addon_path, _SKIN, 'media', os.path.relpath(src, media_src))
                if _copy_if_changed(src, dst):
                    written += 1
        # 3. window XMLs (stock copy backed up first)
        bdir = os.path.join(_BACKUP, aid)
        for name in spec['xml']:
            target = os.path.join(addon_path, _SKIN, '1080i', name)
            current = _read_bytes(target)
            if current is not None and MARKER_XML.encode() not in current:
                os.makedirs(bdir, exist_ok=True)
                if _read_bytes(os.path.join(bdir, name)) != current:
                    with open(os.path.join(bdir, name), 'wb') as f:
                        f.write(current)
                    _write_text(os.path.join(bdir, 'version.txt'), _version(addon_path))
            if _copy_if_changed(os.path.join(_SRC, 'xml', profile, name), target):
                written += 1
        # 4. hooks
        for path, (old, new, crlf) in planned.items():
            if new != old:
                _save_py(path, new, crlf)
                written += 1
        if written:
            return True, '[%s] Patched OK: Glass theme for %s (%d files)' % (aid, label, written)
        return True, '[%s] Already patched – skipping.' % aid
    except Exception as e:
        return False, '[%s] Glass theme: %s' % (aid, e)


def revert(addon_path, profile):
    """Put the stock windows back. Yields nothing if Lucent is not installed."""
    spec = SPECS[profile]
    aid, label = spec['addon_id'], spec['label']
    changed, problems = 0, []
    bdir = os.path.join(_BACKUP, aid)
    for name in spec['xml']:
        target = os.path.join(addon_path, _SKIN, '1080i', name)
        current = _read_bytes(target)
        if current is None or MARKER_XML.encode() not in current:
            continue
        stock = os.path.join(bdir, name)
        if os.path.isfile(stock):
            shutil.copyfile(stock, target)
            changed += 1
        else:
            problems.append(name)
    for rel in sorted({h[0] for h in spec['hooks']}):
        path = os.path.join(addon_path, rel)
        if not os.path.isfile(path):
            continue
        text, crlf = _load_py(path)
        if HOOK_OPEN in text:
            _save_py(path, _strip_hooks(text), crlf)
            changed += 1
    if problems:
        return False, ('[%s] Glass theme: no stock copy of %s – reinstall %s to restore it'
                       % (aid, ', '.join(problems), label))
    if changed:
        return True, '[%s] Patched OK (reverted, toggle off): Glass theme for %s' % (aid, label)
    return None
