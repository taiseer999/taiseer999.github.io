AR = re.compile('[؀-ۿ]')
SUB.sort(key=lambda p: -len(p[0]))
SUB_MAP = dict(SUB)
SUB_RE = re.compile('|'.join(re.escape(o) for o, _ in SUB))


def conv_literal(tok):
    m = re.match(r'(?is)^([rbuf]*)("""|\'\'\'|"|\')(.*)\2$', tok)
    if not m:
        return tok
    pre, q, body = m.groups()
    if body in EXACT:
        return pre + q + EXACT[body] + q
    # one pass, longest phrase first: replaced text is never scanned again,
    # and a phrase already in its new form is left alone (safe to re-run)
    def rep(m):
        return SUB_MAP[m.group(0)]
    body = _guard(body)
    body = SUB_RE.sub(rep, body)
    return pre + q + _unguard(body) + q


_GUARDS = {}


def _guard(body):
    for i, (old, new) in enumerate(SUB):
        if old in new and new in body:
            key = '\x00%d\x00' % i
            _GUARDS[key] = new
            body = body.replace(new, key)
    return body


def _unguard(body):
    for key, new in _GUARDS.items():
        body = body.replace(key, new)
    return body


def do_py(path):
    src = open(path, encoding='utf-8').read()
    lines = src.splitlines(keepends=True)
    offs = [0]
    for l in lines:
        offs.append(offs[-1] + len(l))
    edits = []
    for t in tokenize.generate_tokens(io.StringIO(src).readline):
        if t.type == tokenize.STRING and AR.search(t.string):
            a = offs[t.start[0] - 1] + t.start[1]
            b = offs[t.end[0] - 1] + t.end[1]
            new = conv_literal(t.string)
            if new != t.string:
                edits.append((a, b, new))
    for a, b, new in reversed(edits):
        src = src[:a] + new + src[b:]
    if edits:
        open(path, 'w', encoding='utf-8').write(src)
    return len(edits)


def do_po(path):
    s = open(path, encoding='utf-8').read()
    n = 0
    for old, new in PO.items():
        for k in ('msgid', 'msgstr'):
            a = '%s "%s"\n' % (k, old)
            if a in s:
                s = s.replace(a, '%s "%s"\n' % (k, new))
                n += 1
    open(path, 'w', encoding='utf-8').write(s)
    return n


