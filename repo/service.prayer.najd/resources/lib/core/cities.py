def resolve(city_index, manual_lat, manual_lon, manual_utc):
    """Return (lat, lon, utc). Use the preset unless 'custom' is selected."""
    try:
        i = int(city_index)
    except (TypeError, ValueError):
        i = 0
    if 0 <= i < len(CITIES):
        _n, la, lo, tz = CITIES[i]
        return la, lo, tz

    def _f(v, d):
        try:
            return float(v)
        except (TypeError, ValueError):
            return d
    return _f(manual_lat, 24.7136), _f(manual_lon, 46.6753), _f(manual_utc, 3.0)


def name_of(city_index, manual_name):
    try:
        i = int(city_index)
    except (TypeError, ValueError):
        i = 0
    if 0 <= i < len(CITIES):
        return CITIES[i][0]
    return manual_name or 'مدينتي'
